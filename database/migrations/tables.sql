-- Sprint 2 schema for adherents, weekly goals, equipment, activities, and activity measurements.
-- Existing Sprint 1 activities are preserved; their new foreign keys stay nullable.

BEGIN;

CREATE TABLE IF NOT EXISTS public.adherents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Add missing columns when upgrading an older adherents table.
ALTER TABLE public.adherents
    ADD COLUMN IF NOT EXISTS display_name VARCHAR(100),
    ADD COLUMN IF NOT EXISTS email VARCHAR(255),
    ADD COLUMN IF NOT EXISTS password_hash VARCHAR(255),
    ADD COLUMN IF NOT EXISTS role VARCHAR(20) DEFAULT 'MEMBER',
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP;

DO $adherents_upgrade$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'adherents'
          AND column_name = 'nom'
    ) AND EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'adherents'
          AND column_name = 'prenom'
    ) THEN
        EXECUTE $sql$
            UPDATE public.adherents
            SET display_name = NULLIF(
                CONCAT_WS(' ', NULLIF(BTRIM(prenom), ''), NULLIF(BTRIM(nom), '')),
                ''
            )
            WHERE display_name IS NULL OR BTRIM(display_name) = ''
        $sql$;
    END IF;

    UPDATE public.adherents
    SET role = 'MEMBER'
    WHERE role IS NULL OR BTRIM(role) = '';

    UPDATE public.adherents
    SET created_at = CURRENT_TIMESTAMP
    WHERE created_at IS NULL;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'adherents'
          AND column_name = 'nom'
    ) THEN
        ALTER TABLE public.adherents ALTER COLUMN nom DROP NOT NULL;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'adherents'
          AND column_name = 'prenom'
    ) THEN
        ALTER TABLE public.adherents ALTER COLUMN prenom DROP NOT NULL;
    END IF;

    IF EXISTS (SELECT 1 FROM public.adherents WHERE display_name IS NULL OR BTRIM(display_name) = '') THEN
        RAISE EXCEPTION 'Fill display_name for every adherent before applying this schema';
    END IF;
    IF EXISTS (SELECT 1 FROM public.adherents WHERE email IS NULL OR BTRIM(email) = '') THEN
        RAISE EXCEPTION 'Fill email for every adherent before applying this schema';
    END IF;
    IF EXISTS (SELECT 1 FROM public.adherents WHERE password_hash IS NULL OR BTRIM(password_hash) = '') THEN
        RAISE EXCEPTION 'Fill password_hash for every adherent before applying this schema';
    END IF;
END
$adherents_upgrade$;

ALTER TABLE public.adherents
    ALTER COLUMN display_name SET NOT NULL,
    ALTER COLUMN email SET NOT NULL,
    ALTER COLUMN password_hash SET NOT NULL,
    ALTER COLUMN role SET DEFAULT 'MEMBER',
    ALTER COLUMN role SET NOT NULL,
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN created_at SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS adherents_email_lower_unique
    ON public.adherents (LOWER(email));

CREATE TABLE IF NOT EXISTS public.weekly_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adherent_id BIGINT NOT NULL,
    week_start DATE NOT NULL CHECK (EXTRACT(ISODOW FROM week_start) = 1),
    target_sessions INTEGER NOT NULL CHECK (target_sessions BETWEEN 1 AND 14),
    target_duration_minutes INTEGER NULL CHECK (target_duration_minutes > 0),
    target_distance_km DOUBLE PRECISION NULL CHECK (target_distance_km >= 0),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT weekly_goals_adherent_fk
        FOREIGN KEY (adherent_id)
        REFERENCES public.adherents(id)
        ON DELETE RESTRICT,
    CONSTRAINT weekly_goals_one_per_adherent_week
        UNIQUE (adherent_id, week_start)
);

CREATE TABLE IF NOT EXISTS public.equipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    type VARCHAR(50) NOT NULL,
    category VARCHAR(50) NOT NULL
);

-- Verify the existing Sprint 1 columns before adding relationships.
DO $activities_check$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'activities' AND column_name = 'id'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'activities' AND column_name = 'date'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'activities' AND column_name = 'duration_minutes'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'activities' AND column_name = 'distance_km'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'activities' AND column_name = 'equipment_type'
    ) THEN
        RAISE EXCEPTION 'The existing public.activities table does not match the Sprint 1 schema';
    END IF;
END
$activities_check$;

ALTER TABLE public.activities
    ADD COLUMN IF NOT EXISTS adherent_id BIGINT NULL,
    ADD COLUMN IF NOT EXISTS equipment_id BIGINT NULL;

DO $activity_constraints$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'activities_adherent_fk'
          AND conrelid = 'public.activities'::regclass
    ) THEN
        ALTER TABLE public.activities
            ADD CONSTRAINT activities_adherent_fk
            FOREIGN KEY (adherent_id)
            REFERENCES public.adherents(id)
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'activities_equipment_fk'
          AND conrelid = 'public.activities'::regclass
    ) THEN
        ALTER TABLE public.activities
            ADD CONSTRAINT activities_equipment_fk
            FOREIGN KEY (equipment_id)
            REFERENCES public.equipments(id)
            ON DELETE RESTRICT;
    END IF;
END
$activity_constraints$;

CREATE INDEX IF NOT EXISTS activities_adherent_date_idx
    ON public.activities (adherent_id, date DESC, id DESC);

CREATE INDEX IF NOT EXISTS activities_equipment_idx
    ON public.activities (equipment_id);

CREATE TABLE IF NOT EXISTS public.activity_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL,
    elapsed_seconds INTEGER NOT NULL CHECK (elapsed_seconds >= 0),
    speed DOUBLE PRECISION NOT NULL CHECK (speed >= 0),
    distance_km DOUBLE PRECISION NOT NULL CHECK (distance_km >= 0),
    CONSTRAINT activity_stats_activity_fk
        FOREIGN KEY (activity_id)
        REFERENCES public.activities(id)
        ON DELETE CASCADE,
    CONSTRAINT activity_stats_activity_elapsed_unique
        UNIQUE (activity_id, elapsed_seconds)
);

CREATE INDEX IF NOT EXISTS activity_stats_activity_elapsed_idx
    ON public.activity_stats (activity_id, elapsed_seconds);

GRANT SELECT, INSERT, UPDATE, DELETE
    ON public.adherents, public.weekly_goals, public.equipments, public.activities, public.activity_stats
    TO fitness_app;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO fitness_app;

COMMIT;
